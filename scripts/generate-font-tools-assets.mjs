import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const fontkit = require('fontkit')
const repoRoot = path.resolve(new URL('.', import.meta.url).pathname, '..')
const fontDirectory = path.join(repoRoot, 'docs/doc_site/public/font_tools/fonts')
const outputDirectory = path.join(repoRoot, 'docs/doc_site/public/font_tools')
const supportedExtensions = new Set(['.otf', '.ttf', '.woff', '.woff2'])

function cssFamily(value) {
  return String(value).replaceAll('\\', '\\\\').replaceAll('"', '\\"')
}

function cssUrl(value) {
  return value.replaceAll('\\', '/').replaceAll(' ', '%20').replaceAll('"', '%22')
}

function familyName(font, filePath) {
  const fileName = path.basename(filePath, path.extname(filePath))
  const legacyName = fileName.match(/^\d+-(.+)$/)?.[1]
  if (legacyName) return legacyName.replaceAll('-', ' ').trim()

  const rawFamily = font.familyName || font.fullName || path.basename(filePath, path.extname(filePath))
  return rawFamily
    .replace(/\s+(Thin|ExtraLight|Light|Medium|SemiBold|Bold|ExtraBold|Black)$/i, '')
    .trim()
}

function fontWeight(font) {
  const weight = Number(font['OS/2']?.usWeightClass || font.weightClass || 400)
  return Number.isFinite(weight) && weight > 0 ? weight : 400
}

function fontStyle(font) {
  return font['OS/2']?.fsSelection?.italic || /italic|oblique/i.test(String(font.subfamilyName || ''))
    ? 'italic'
    : 'normal'
}

function inspectFont(filePath) {
  const font = fontkit.openSync(filePath)
  const family = familyName(font, filePath)
  return {
    file: path.basename(filePath),
    family,
    style: fontStyle(font),
    weight: fontWeight(font)
  }
}

if (!fs.existsSync(fontDirectory)) {
  throw new Error(`Font directory does not exist: ${fontDirectory}`)
}

const files = fs.readdirSync(fontDirectory)
  .filter(file => supportedExtensions.has(path.extname(file).toLowerCase()))
  .sort((left, right) => left.localeCompare(right, 'en', { sensitivity: 'base' }))

if (!files.length) {
  throw new Error(`No font files found in ${fontDirectory}`)
}

const inspected = files.map(file => inspectFont(path.join(fontDirectory, file)))
const families = new Map()
for (const font of inspected) {
  if (!families.has(font.family)) families.set(font.family, [])
  families.get(font.family).push(font)
}

const manifest = [...families.entries()]
  .sort(([left], [right]) => left.localeCompare(right, 'en', { sensitivity: 'base' }))
  .map(([family, faces]) => ({
    name: family,
    family,
    fallback: 'sans-serif',
    styles: [...new Set(faces.map(face => face.style))],
    weights: [...new Set(faces.map(face => face.weight))].sort((left, right) => left - right),
    files: faces.map(face => ({
      file: face.file,
      style: face.style,
      weight: face.weight
    }))
  }))

const manifestSource = `window.SDD_FONT_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`
const css = [
  '/* Generated by scripts/generate-font-tools-assets.mjs. */',
  ...inspected.map(font => [
    '@font-face {',
    `  font-family: "${cssFamily(font.family)}";`,
    `  font-style: ${font.style};`,
    `  font-weight: ${font.weight};`,
    '  font-display: swap;',
    `  src: url("fonts/${cssUrl(font.file)}") format("${path.extname(font.file).toLowerCase() === '.woff2' ? 'woff2' : path.extname(font.file).toLowerCase() === '.woff' ? 'woff' : 'opentype'}");`,
    '}',
    ''
  ].join('\n'))
].join('\n')

fs.writeFileSync(path.join(outputDirectory, 'font-manifest.js'), manifestSource)
fs.writeFileSync(path.join(outputDirectory, 'fonts.css'), `${css}\n`)
console.log(`Generated font manifest and CSS for ${manifest.length} families from ${files.length} files.`)
